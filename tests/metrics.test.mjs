import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {stats,daily} from '../src/lib/metrics.js';
import {dateMinus} from '../src/lib/format.js';
import {makeAlerts,selectAlerts} from '../src/lib/alerts.js';
import {toCSV} from '../src/lib/csv.js';
const data=JSON.parse(await readFile(new URL('../data/app_data.json',import.meta.url),'utf-8'));
const {facts:F,teams:T,manifest:M}=data;
const end=M.data_end, start=dateMinus(end,29), priorEnd=dateMinus(start,1), priorStart=dateMinus(priorEnd,29);
const current=F.filter(r=>r.date>=start&&r.date<=end),prior=F.filter(r=>r.date>=priorStart&&r.date<=priorEnd);
const alerts=makeAlerts(current,prior,T,M.targets);
test('dataset has 12 teams and 2,880 workstream-day facts',()=>{assert.equal(T.length,12);assert.equal(F.length,2880);});
test('last 30 days contain 720 workstream-days',()=>assert.equal(current.length,720));
test('date subtraction crosses months correctly',()=>assert.equal(dateMinus('2026-07-01',1),'2026-06-30'));
test('KPI SLA is ratio of sums',()=>{const s=stats(current);assert.equal(s.sla,s.onTime/s.closed);});
test('margin matches fact-level totals',()=>{const s=stats(F);assert.equal(s.revenue-s.cost,F.reduce((a,r)=>a+r.revenue_inr-r.cost_inr,0));});
test('backlog is a latest-date stock, not a sum across the selected days',()=>assert.equal(stats(F).backlog,F.filter(x=>x.date===end).reduce((a,r)=>a+r.backlog_close,0)));
test('daily aggregation has 120 days',()=>assert.equal(daily(F).length,120));
test('West Claims SLA breach appears from synthetic scenario',()=>assert.ok(alerts.some(a=>a.team.team_id==='WE-CLM'&&a.kind==='SLA'&&a.value<.90)));
test('North Support quality breach appears',()=>assert.ok(alerts.some(a=>a.team.team_id==='NO-CST'&&a.kind==='Quality'&&a.value<.90)));
test('South Data margin compression appears',()=>assert.ok(alerts.some(a=>a.team.team_id==='SO-DAT'&&a.kind==='Margin'&&a.value<.2)));
test('East Data workforce shortage appears',()=>assert.ok(alerts.some(a=>a.team.team_id==='EA-DAT'&&a.kind==='Workforce')));
test('role filter changes exception visibility',()=>{assert.ok(selectAlerts(alerts,'Executive').every(x=>['SLA','Margin','Backlog'].includes(x.kind)));assert.ok(selectAlerts(alerts,'Operations').some(x=>x.kind==='Workforce'));});
test('CSV quotes fields and mitigates formula injection',()=>{const c=toCSV([{name:'a,"b"',note:'=1+1'}]);assert.ok(c.includes('a,""b""'));assert.ok(c.includes("'=1+1"));});
